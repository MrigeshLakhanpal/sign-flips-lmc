"""v2 verdicts: H1-k, H4a-c, H5, H7 and the title rule (v2_rules.md, Sections 6 and 8). Written by Claude, 19 Oct 2026.

python src/hypotheses_v2.py      ->  prints and writes results_v2/verdicts.md
Thresholds are exactly the pre-registered ones; nothing here is tuned.
"""
import argparse, json, pathlib
import numpy as np
import pandas as pd
from mechanism import spearman_ci

EPS = 0.005                                   # 0.5 points, as a fraction
ap = argparse.ArgumentParser()
ap.add_argument("--in-dir", default="results_v2")
a = ap.parse_args()
d = pathlib.Path(a.in_dir)
frozen = json.load(open(d / "stage1_frozen.json"))["tasks"]


def evaluate(P):
    """P: pairs.csv rows of one task. Returns dict of verdicts (unflagged pairs only for H4/H5)."""
    out = {"pairs": P["pair"].nunique()}
    out["h1"] = bool(P.drop_duplicates("pair")["h1_pass"].all())
    U = P[~P["flagged"]]
    out["pairs_unflagged"] = U["pair"].nunique()
    if "exact_sign" not in set(U["mode"]):
        return out
    W = U.pivot(index="pair", columns="mode")
    es, ep, ws = W["err_barrier"]["exact_sign"], W["err_barrier"]["exact_perm"], W["err_barrier"]["wm_sign"]
    flips = W["n_flips"]["exact_sign"] >= 1
    out["exact_sign_uq_points"] = 100 * float(np.percentile(es, 75))
    out["H4a"] = bool(np.percentile(es, 75) <= EPS)
    out["flip_pairs"] = int(flips.sum())
    out["exact_perm_median_flip_pairs_points"] = 100 * float(np.median(ep[flips])) if flips.any() else None
    out["H4b"] = bool(flips.any() and np.median(ep[flips]) > 0.02)
    out["wm_sign_within_eps"] = float(np.mean(np.abs(ws - es) <= EPS))
    out["H4c"] = bool(out["wm_sign_within_eps"] >= 0.80)
    fr = {}
    for m in ("err_barrier", "test_err_barrier", "loss_barrier", "cal_loss_barrier"):
        fr[m] = float(np.mean(W[m]["exact_perm"][flips] > W[m]["exact_sign"][flips])) if flips.any() else None
    out["H5_fractions"] = fr
    out["H5"] = bool(flips.any() and all(v >= 0.90 for v in fr.values()))
    return out


res, mech = {}, []
for task in sorted(frozen):
    p = d / task / "pairs.csv"
    if frozen[task]["hstar"] is None or not p.exists():
        res[task] = {"analyzable": False, "hstar": frozen[task]["hstar"]}
        continue
    r = evaluate(pd.read_csv(p))
    r.update(analyzable="H4a" in r, hstar=frozen[task]["hstar"])
    res[task] = r
    m = d / task / "mechanism.csv"
    if m.exists():
        mech.append(pd.read_csv(m))

h7 = None
if mech:
    Mx = pd.concat(mech)
    Mx = Mx[(~Mx["flagged"]) & (Mx["n_flipped"] >= 1)]
    if len(Mx) >= 3:
        rho, lo, hi = spearman_ci(Mx["M"], Mx["B_F"])
        h7 = dict(n_pairs=len(Mx), rho=rho, ci=[lo, hi],
                  verdict="supported" if lo > 0 else ("weak" if rho > 0 else "not supported"))

# Title rule (Section 8)
an = [t for t, r in res.items() if r.get("analyzable")]
holds = [t for t in an if res[t]["H4a"]]
poly_an = [t for t in an if t != "T0"]
if "T0" in an and len(poly_an) >= 3 and len(holds) == len(an):
    title = "A Missing Sign Symmetry Accounts for the Linear-Mode-Connectivity Barrier in Minimal-Width Sigmoid Networks"
elif holds == ["T0"]:
    title = "... in Width-3 Sigmoid Networks"
elif holds:
    title = f"... in Small Sigmoid Networks  (H4a holds for: {', '.join(holds)})"
else:
    title = "No title rule applies: H4a holds for no task. Report as a negative result."

lines = ["# v2 verdicts (generated by src/hypotheses_v2.py)", ""]
for t, r in res.items():
    lines.append(f"## {t}"); lines += [f"- {k}: {v}" for k, v in r.items()]; lines.append("")
lines += ["## H7 (pooled)", f"- {h7}", "", "## Title rule (Section 8)", f"- {title}", ""]
(d / "verdicts.md").write_text("\n".join(lines))
print("\n".join(lines))
