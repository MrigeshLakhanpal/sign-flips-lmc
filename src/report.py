"""A reporting: bootstrap intervals, Tables 1-2, and Figure 2 with intervals.
Check with:  python tests/test_report.py   (made-up numbers, no coffee data)
Run:         python src/report.py          (reads results/ and, if present, results_b1/)
Writes results/report_tables.md and figures/fig2_barrier_ci.png. Changes no verdict: intervals only
describe how precise each dated number is.
"""
import pathlib
import numpy as np
import pandas as pd

N_BOOT = 10000   # fixed before the run (H1b and statistics plan)


def median_ci(x, n_boot=N_BOOT, seed=0):
    """95% bootstrap interval for the median of x (resample pairs with replacement)."""
    x = np.asarray(x, float)
    rng = np.random.default_rng(seed)
    meds = np.empty(n_boot)
    for k in range(n_boot):
        meds[k] = np.median(rng.choice(x, size=len(x), replace=True)) 
    return np.percentile(meds, [2.5, 97.5])                      


def paired_diff_ci(a, b, n_boot=N_BOOT, seed=0):
    """Median of the per-pair differences b - a, and its 95% bootstrap interval.
    a[k] and b[k] must be the same pair (same two seeds) under two modes."""
    d = b - a                                                     
    return float(np.median(d)), median_ci(d, n_boot, seed)


def fmt(m, ci):
    return f"{m:.2f} [{ci[0]:.2f}, {ci[1]:.2f}]"


def main():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    B = pd.read_csv("results/barriers.csv")
    B["err"] = B.err_barrier * 100; B["test"] = B.test_err_barrier * 100
    piv = B.pivot_table(index=["width", "pair"], columns="mode", values="err")
    lines = ["# Probe B report tables (generated by src/report.py)", "",
             "Training error barrier in points; median [95% bootstrap interval over pairs, 10,000 resamples].", ""]

    # Table A: every width and mode
    lines += ["## Table A. Error barrier per width and mode", "",
              "| Width | Mode | Pairs | Error barrier | Calibrated loss barrier (median) | Test error barrier (median) |",
              "|---|---|---|---|---|---|"]
    for (w, m), g in B.groupby(["width", "mode"]):
        lines.append(f"| {w} | {m} | {len(g)} | {fmt(np.median(g.err), median_ci(g.err))} | "
                     f"{np.median(g.cal_loss_barrier):.3f} | {np.median(g.test):.2f} |")

    def paired_rows(title, comps):
        out = ["", f"## {title}", "", "| Width | Comparison | Pairs | Median of per-pair difference |", "|---|---|---|---|"]
        for a, b, P in comps:
            for w in sorted(P.index.get_level_values(0).unique()):
                sub = P.loc[w][[a, b]].dropna()
                if len(sub):
                    m, ci = paired_diff_ci(sub[a].to_numpy(), sub[b].to_numpy())
                    out.append(f"| {w} | {b} − {a} | {len(sub)} | {fmt(m, ci)} |")
        return out

    # Table 1 (Q3): weight matching minus brute force; exact brute force from B1 if available
    comps1 = [("bf_perm", "wm", piv), ("bf_sign", "wm_sign", piv)]
    if pathlib.Path("results_b1/b1_barriers.csv").exists():
        E = pd.read_csv("results_b1/b1_barriers.csv"); E["err"] = E.err_barrier * 100
        pe = E.pivot_table(index=["width", "pair"], columns="mode", values="err").join(piv[["wm", "wm_sign"]])
        comps1 += [("exact_perm", "wm", pe), ("exact_sign", "wm_sign", pe)]
    lines += paired_rows("Table 1 (Q3). Weight matching minus brute force (positive = weight matching worse)", comps1)

    # Table 2 (Q4): with flips minus without flips (negative = flips lower the barrier)
    comps2 = [("wm", "wm_sign", piv), ("bf_perm", "bf_sign", piv)]
    if pathlib.Path("results_b1/b1_barriers.csv").exists():
        comps2 += [("exact_perm", "exact_sign", pe)]
    lines += paired_rows("Table 2 (Q4). With sign flips minus without (negative = flips lower the barrier)", comps2)

    pathlib.Path("results/report_tables.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # Figure 2: median with 95% bootstrap interval, per mode
    fig, ax = plt.subplots(figsize=(6.5, 4))
    for k, m in enumerate(["none", "wm", "wm_sign", "bf_sign"]):
        g = B[B["mode"] == m]
        ws = sorted(g.width.unique())
        if not ws:
            continue
        med = np.array([np.median(g[g.width == w].err) for w in ws])
        ci = np.array([median_ci(g[g.width == w].err) for w in ws])
        x = np.array(ws) * (1 + 0.05 * (k - 1.5))
        ax.errorbar(x, med, yerr=[med - ci[:, 0], ci[:, 1] - med], marker="o", ms=4, capsize=3, label=m)
    ax.axhline(0.5, color="grey", lw=0.7, ls="--", label="ε = 0.5")
    ax.set_xscale("log", base=2)
    ax.set(xlabel="Hidden width", ylabel="Train error barrier (points)",
           title="Barrier vs width (median, 95% bootstrap interval over pairs)")
    ax.legend(frameon=False, fontsize=8); fig.tight_layout()
    pathlib.Path("figures").mkdir(exist_ok=True); fig.savefig("figures/fig2_barrier_ci.png", dpi=200)
    print("\n".join(lines)); print("\nwrote results/report_tables.md and figures/fig2_barrier_ci.png")


if __name__ == "__main__":
    main()
